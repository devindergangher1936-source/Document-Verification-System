"""PDF structure and metadata forensics.

Checks are modelled on common PDF-forensics heuristics (incremental updates,
producer/creator tools, date mismatches, font-subset reuse, active content)
as used by tools such as Didier Stevens' pdf-parser / pdfid.
"""
import io
import re
from datetime import datetime

from PIL import Image
from pypdf import PdfReader

EDITOR_TOOLS = [
    "photoshop", "gimp", "illustrator", "canva", "ilovepdf", "smallpdf", "sejda",
    "pdfescape", "pdffiller", "dochub", "foxit phantompdf", "foxit pdf editor",
    "nitro", "pdf-xchange editor", "inkscape", "affinity", "paint.net", "pixlr",
    "pdfelement", "wondershare", "soda pdf", "pdf24", "libreoffice draw",
]

SUBSET_RE = re.compile(r"^[A-Z]{6}\+")


def _parse_pdf_date(value):
    if not value:
        return None
    m = re.match(r"D?:?(\d{4})(\d{2})?(\d{2})?(\d{2})?(\d{2})?(\d{2})?", str(value))
    if not m:
        return None
    parts = [int(p) if p else d for p, d in zip(m.groups(), (0, 1, 1, 0, 0, 0))]
    try:
        return datetime(*parts)
    except ValueError:
        return None


def _font_subset_conflicts(reader):
    """Same base font embedded as several different subsets on one page.

    When text is edited in a PDF editor, the new glyphs are often embedded as a
    fresh subset (e.g. ABCDEF+Arial and GHIJKL+Arial on the same page).
    """
    conflicts = []
    for page_no, page in enumerate(reader.pages, 1):
        try:
            fonts = page.get("/Resources", {}).get_object().get("/Font", {}).get_object()
        except Exception:
            continue
        by_base = {}
        for ref in fonts.values():
            try:
                base = str(ref.get_object().get("/BaseFont", ""))
            except Exception:
                continue
            name = base.lstrip("/")
            if SUBSET_RE.match(name):
                by_base.setdefault(name[7:], set()).add(name[:6])
        for base, prefixes in by_base.items():
            if len(prefixes) > 1:
                conflicts.append({"page": page_no, "font": base, "subsets": len(prefixes)})
    return conflicts


def analyze_pdf(path, ela_out=None):
    from .image_checks import error_level_analysis

    findings = []
    meta = {}
    raw = open(path, "rb").read()

    eof_count = raw.count(b"%%EOF")
    meta["revisions"] = eof_count
    has_sig = b"/Sig" in raw and b"/ByteRange" in raw
    meta["digitally_signed"] = has_sig

    for marker, label in [(b"/JavaScript", "JavaScript"), (b"/Launch", "Launch action"),
                          (b"/EmbeddedFile", "embedded files")]:
        if marker in raw:
            findings.append(("medium", "security", f"PDF contains {label}",
                             "Unusual for ordinary documents and can be used for malicious behaviour."))

    try:
        reader = PdfReader(io.BytesIO(raw))
    except Exception as exc:
        findings.append(("high", "structure", "PDF could not be parsed", str(exc)[:200]))
        return meta, findings, ""

    if reader.is_encrypted:
        try:
            reader.decrypt("")
        except Exception:
            pass
        findings.append(("low", "structure", "PDF is encrypted", "Content may not be fully inspectable."))

    info = {}
    try:
        for k, v in (reader.metadata or {}).items():
            info[k.lstrip("/")] = str(v)[:200]
    except Exception:
        pass
    meta["info"] = info
    meta["pages"] = len(reader.pages)

    tools = f"{info.get('Producer', '')} {info.get('Creator', '')}".lower()
    hit = next((t for t in EDITOR_TOOLS if t in tools), None)
    if hit:
        findings.append(("high", "metadata", f"Document was produced/edited with '{hit}'",
                         f"Producer: {info.get('Producer', '-')}; Creator: {info.get('Creator', '-')}. "
                         "Bank statements, certificates and govt. documents are normally generated by "
                         "server-side systems, not consumer editors."))
    if not info.get("Producer") and not info.get("Creator"):
        findings.append(("low", "metadata", "Producer/Creator metadata missing",
                         "Metadata is sometimes stripped to hide the editing tool."))

    created = _parse_pdf_date(info.get("CreationDate"))
    modified = _parse_pdf_date(info.get("ModDate"))
    if created and modified:
        delta = (modified - created).total_seconds()
        if delta < -60:
            findings.append(("medium", "metadata", "Modification date is before creation date",
                             "Indicates metadata manipulation."))
        elif delta > 300:
            findings.append(("medium", "metadata", "Document was modified after it was created",
                             f"Created {created:%Y-%m-%d %H:%M}, modified {modified:%Y-%m-%d %H:%M}."))
    if created and created > datetime.now():
        findings.append(("medium", "metadata", "Creation date is in the future", str(created)))

    if eof_count > 1:
        sev = "low" if has_sig else "medium"
        findings.append((sev, "structure", f"PDF has {eof_count} revisions (incremental updates)",
                         "Content was appended after the original save. Normal for signed or form-filled "
                         "PDFs; otherwise a sign of later editing." if has_sig else
                         "Content was appended after the original save - a common sign of later editing."))
    if has_sig:
        findings.append(("info", "structure", "PDF contains a digital signature",
                         "Validate the signature in Adobe Reader to confirm it is intact and trusted."))

    conflicts = _font_subset_conflicts(reader)
    if conflicts:
        meta["font_conflicts"] = conflicts
        pages = sorted({c["page"] for c in conflicts})
        findings.append(("medium", "structure", "Same font embedded as multiple subsets",
                         f"Pages {pages}: typical when text is edited in a PDF editor after generation."))

    text_parts = []
    for page in reader.pages[:20]:
        try:
            text_parts.append(page.extract_text() or "")
        except Exception:
            pass
    text = "\n".join(text_parts)

    # Run ELA on the largest embedded JPEG (scanned documents).
    jpeg = None
    try:
        for page in reader.pages[:5]:
            for im in page.images:
                if im.name.lower().endswith((".jpg", ".jpeg")) and (jpeg is None or len(im.data) > len(jpeg)):
                    jpeg = im.data
    except Exception:
        pass
    if jpeg:
        try:
            stats, ela_findings = error_level_analysis(Image.open(io.BytesIO(jpeg)), ela_out)
            meta["ela"] = stats
            findings += ela_findings
        except Exception:
            pass

    return meta, findings, text
